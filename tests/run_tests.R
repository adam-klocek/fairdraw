check <- function(ok, label) {
  if (!isTRUE(ok)) stop(paste("FAILED:", label), call. = FALSE)
  checks <<- checks + 1L; cat("PASS", label, "\n")
}
fails <- function(expr) inherits(tryCatch({force(expr); NULL}, error = identity), "error")
